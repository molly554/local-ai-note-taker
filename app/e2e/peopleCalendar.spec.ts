import { _electron as electron, expect, test } from '@playwright/test'
import { mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

for (const theme of ['light', 'dark'] as const) test(`split metadata popovers stay separate in a short note (${theme})`, async () => {
  const app = await electron.launch({ args: [join(import.meta.dirname, '../out/main/index.js')], env: {
    ...process.env, YOGURT_FAKE: '1', YOGURT_USER_DATA: mkdtempSync(join(tmpdir(), 'yogurt-e2e-')),
  } })
  try {
    const page = await app.firstWindow()
    await expect(page.getByTestId('home')).toBeVisible()
    await app.evaluate(() => (globalThis as unknown as { __fake__: { manyMeetings(o: unknown): void } }).__fake__.manyMeetings({ n: 1, clean: true }))
    const [meeting] = await page.evaluate(() => window.yogurt.meetings.cards({ limit: 1 }))
    const events = [{ id: 'linked-event', title: 'Planning with Jamie', start: new Date(meeting.startedAt).toISOString(), end: new Date(meeting.startedAt + 1_800_000).toISOString(),
      attendees: [{ name: 'Jamie Quill', email: 'jamie@example.com' }], url: 'https://meet.google.com/fak-eeve-ntx', calendarId: 'work', calendar: 'Work', calendarSource: 'owner@example.com' }]
    const next = new Date(meeting.startedAt); next.setDate(next.getDate() + 1)
    events.push({ ...events[0], id: 'next-day-event', title: 'Next day review', start: next.toISOString(), end: new Date(+next + 1_800_000).toISOString() })
    await app.evaluate((_e, events) => (globalThis as unknown as { __fake__: { calendarEvents(events: unknown[]): void } }).__fake__.calendarEvents(events), events)
    await page.evaluate(theme => window.yogurt.settings.setTheme(theme), theme)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => !w.webContents.getURL().includes('#'))!.setContentSize(720, 520))
    await page.reload()
    await page.getByTestId('past-note').click()
    await page.getByTestId('note-date').click()
    const date = page.getByTestId('note-date-card')
    await expect(date).toContainText('25 min')
    await expect(date.getByTestId('people-list')).toHaveCount(0)
    await expect(date.getByRole('link')).toHaveCount(0)
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('note-date')).toBeFocused()
    await page.getByTestId('note-attendees').click()
    await expect(page.getByTestId('people-add')).toBeFocused()
    await expect(page.getByTestId('people-card')).not.toContainText('Who was there')
    await page.keyboard.press('Escape')
    await page.getByTestId('note-date').click()
    await page.getByTestId('note-date-events-toggle').click()
    await expect(page.getByTestId('note-date-event').first()).toBeFocused()
    await expect(page.getByTestId('note-date-event').first()).toContainText('Jamie')
    // An event disappearing between listing and selection must be a retryable error.
    await app.evaluate(() => (globalThis as any).__fake__.calendarEvents([]))
    await page.getByTestId('note-date-event').filter({ hasText: 'Planning with Jamie' }).press('Enter')
    await expect(date.getByRole('alert')).toContainText("Yogurt couldn't update the calendar link")
    expect((await page.evaluate(id => window.yogurt.meetings.get(id), meeting.id))?.eventId).toBeNull()
    await app.evaluate((_e, events) => (globalThis as any).__fake__.calendarEvents(events), events)
    await page.getByTestId('note-date-event').filter({ hasText: 'Planning with Jamie' }).press('Enter')
    await expect(date).toContainText('Planning with Jamie')
    await expect(date).toContainText('Work')
    await expect(date).toContainText('owner@example.com')
    await expect(date.getByRole('button', { name: 'Open note', exact: true })).toHaveCount(0)
    await expect(date.getByRole('link', { name: 'Join meeting' })).toHaveAttribute('href', events[0].url)
    await expect(date.getByRole('link', { name: 'Join meeting' })).toHaveClass('workspace-button agenda-open-note')
    await expect(date.getByRole('link', { name: 'Join meeting' })).toHaveCSS('height', '28px')
    await expect(date.locator('.agenda-inspector-actions')).toHaveCSS('justify-content', 'flex-end')
    await expect(date.getByTestId('people-list')).toHaveCount(0)
    await page.getByTestId('note-date-events-toggle').click()
    await page.getByTestId('note-date-next').click()
    await page.getByTestId('note-date-event').filter({ hasText: 'Next day review' }).click()
    await expect(page.getByTestId('note-title')).toHaveText('Next day review')
    await page.keyboard.press('Escape')
    await page.reload()
    await page.getByTestId('note-date').click()
    await expect(date).toContainText('Next day review')
    await expect(date).not.toContainText('Calendar event unavailable')
    await page.getByTestId('note-date-events-toggle').click()
    await page.getByTestId('note-date-previous').click()
    await expect(page.getByTestId('note-date-event').first()).toContainText('Planning with Jamie')
    await page.getByTestId('note-date-unlink').click()
    await expect(page.getByTestId('note-date-events-toggle')).toHaveText('Link to a calendar event')
    await expect(page.getByTestId('note-date-events-toggle')).toHaveClass('workspace-button agenda-open-note')
    await expect(page.getByTestId('note-title')).toHaveText('Next day review')
    expect((await page.evaluate(id => window.yogurt.meetings.get(id), meeting.id))?.startedAt).toBe(meeting.startedAt)
    await page.getByTestId('note-attendees').click()
    await expect(date).toHaveCount(0)
    const people = page.getByTestId('people-card')
    await expect(people.getByTestId('people-email')).toHaveText('jamie@example.com')
    await expect(people).not.toContainText('Planning with Jamie')
    // a mouse-opened card shows no row actions until hovered or reached by keyboard
    await expect(people.getByTestId('people-edit')).toHaveCSS('opacity', '0')
    await people.getByTestId('people-name').focus()
    await page.keyboard.press('Tab')
    await expect(people.getByTestId('people-edit')).toBeFocused()
    await expect(people.getByTestId('people-edit')).toHaveCSS('opacity', '1')
    const bounds = await people.boundingBox(), note = await page.getByTestId('note').boundingBox()
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(note!.y + note!.height)
    await page.keyboard.press('Escape')
    await expect(page.getByTestId('note-attendees')).toBeFocused()
  } finally { await app.close() }
})
